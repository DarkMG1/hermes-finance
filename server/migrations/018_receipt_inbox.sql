-- Receipt inbox: photos taken before the bank charge exists, linked to it later.
CREATE TABLE inbox_receipts (
  id TEXT PRIMARY KEY,                    -- generated by the phone, so a retried upload can't duplicate
  jpeg BLOB,                              -- NULL once linked: the photo moved to receipts
  bytes INTEGER NOT NULL,
  captured_at TEXT NOT NULL,
  read_at TEXT,
  read_failed INTEGER NOT NULL DEFAULT 0,
  model TEXT,
  merchant TEXT,
  purchase_date TEXT,
  total_cents INTEGER,
  tax_cents INTEGER,
  tip_cents INTEGER,
  fees_cents INTEGER,
  items TEXT,                             -- JSON [{ name, amountCents, people }]
  tagged INTEGER NOT NULL DEFAULT 0,
  linked_transaction_id TEXT REFERENCES transactions(id) ON DELETE SET NULL,
  linked_at TEXT,
  split_applied INTEGER NOT NULL DEFAULT 0,
  dismissed_at TEXT
);
CREATE INDEX inbox_receipts_waiting ON inbox_receipts(linked_at, captured_at);
